# ---------------------------------------------------------------- generated deliverables
def docx_bytes(title: str, lines: list[str]) -> bytes:
    from docx import Document

    doc = Document()
    doc.add_heading(title, level=0)
    for line in lines:
        doc.add_paragraph(line)
    doc.add_paragraph("MOCK - generated by mock/mock_server.py, no model was used.")
    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()


def xlsx_bytes(header: list[str], rows: list[list[Any]]) -> bytes:
    from openpyxl import Workbook

    wb = Workbook()
    ws = wb.active
    ws.append(header)
    for row in rows:
        ws.append(row)
    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


# ---------------------------------------------------------------- scripted runs
@dataclass
class Script:
    route: RouteDecision
    plan: list[PlanStep]
    events: list[dict[str, Any]]          # {"type", "title", "data", "step"}; "$artifact:N" placeholders
    files: list[tuple[str, ArtifactKind, bytes, str]]   # filename, kind, content, preview
    answer: str


def _route(task_type: TaskType, reason: str, layer: str = "rule") -> RouteDecision:
    model = next(m for m in MODELS if task_type in m.tasks)
    return RouteDecision(task_type=task_type, model_id=model.id, ollama_name=model.ollama_name, reason=reason,
                         layer=layer, confidence=1.0 if layer != "default" else 0.4)


def _tool_events(step: int, tool: str, args: dict, summary: str, model: Optional[str] = None,
                 artifacts: tuple[int, ...] = ()) -> list[dict[str, Any]]:
    out = [{"type": "step_start", "step": step, "title": f"Step {step}: {tool}", "data": {"index": step, "title": tool}},
           {"type": "tool_call", "step": step, "title": tool, "data": {"tool": tool, "args": args}}]
    if model:
        out.append({"type": "llm_call", "step": step, "title": f"{model}: {tool}",
                    "data": {"model_id": model, "purpose": tool, "duration_ms": 1200, "tokens_out": 180}})
    out += [{"type": "artifact", "step": step, "title": "file", "data": {"artifact": f"$artifact:{i}"}} for i in artifacts]
    out.append({"type": "tool_result", "step": step, "title": f"{tool}: ok",
                "data": {"tool": tool, "ok": True, "summary": summary, "duration_ms": 900}})
    return out


def _finish(step: int, answer: str) -> list[dict[str, Any]]:
    return _tool_events(step, "finish", {"answer": answer}, "Finished.") + [
        {"type": "final", "step": None, "title": "Done", "data": {"answer": answer}}]


def _head(route: RouteDecision, plan: list[PlanStep]) -> list[dict[str, Any]]:
    return [{"type": "route", "step": None, "title": f"Routed to {route.task_type.value} ({route.ollama_name})",
             "data": {"decision": route.model_dump(mode="json")}},
            {"type": "plan", "step": None, "title": f"Plan with {len(plan)} steps",
             "data": {"steps": [p.model_dump(mode="json") for p in plan]}}]


def inspection_script() -> Script:
    fx = load_fixture()
    route, plan = RouteDecision.model_validate(fx["route"]), [PlanStep.model_validate(p) for p in fx["plan"]]
    events = []
    for raw in fx["events"]:
        event = copy.deepcopy(raw)
        data = event["data"]
        if data.get("decision") == "$route":
            data["decision"] = route.model_dump(mode="json")
        if data.get("steps") == "$plan":
            data["steps"] = [p.model_dump(mode="json") for p in plan]
        if data.get("artifact") == "$artifact":
            data["artifact"] = "$artifact:0"
        events.append(event)
    art = fx["artifact"]
    word = docx_bytes("INSPECTION APPROVAL NOTE (mock)", [art["preview"], fx["final_answer"]])
    return Script(route, plan, events, [(art["filename"], ArtifactKind.DOCX, word, art["preview"])], fx["final_answer"])


def code_script() -> Script:
    route = _route(TaskType.CODING, "Rule: Coding keywords -> code specialist model (matched 'function')")
    plan = [PlanStep(index=1, title="Write, test and run the calculation code", tool="run_code_task"),
            PlanStep(index=2, title="Report the calculation steps", tool="finish")]
    tests = "from solution import pipe_wall_thickness\n\n\ndef test_known():\n    assert round(pipe_wall_thickness(10, 200, 138), 3) == 7.246\n"
    answer = "t = 10 * 200 / (2 * 138) = 7.246 mm. Code and tests passed in the sandbox (mock)."
    events = _head(route, plan) + _tool_events(1, "run_code_task", {"request": "pipe wall thickness"},
                                               "Code passed its tests: 1 passed, 0 failed, 1 attempt(s).",
                                               model="coder", artifacts=(0, 1)) + _finish(2, answer)
    files = [("solution_mock.py", ArtifactKind.PY, SOLUTION_PY.encode(), SOLUTION_PY),
             ("test_solution_mock.py", ArtifactKind.PY, tests.encode(), tests)]
    return Script(route, plan, events, files, answer)


def pid_script() -> Script:
    route = _route(TaskType.VISION, "Rule: Image attached -> vision-capable model")
    plan = [PlanStep(index=1, title="Read the P&ID drawing in tiles", tool="read_document"),
            PlanStep(index=2, title="Extract the tag list to Excel", tool="extract_pid_tags"),
            PlanStep(index=3, title="Summarise the tag counts", tool="finish")]
    rows = [["P-201A", "Pump"], ["P-201B", "Pump"], ["FT-201", "Flow transmitter"], ["V-201", "Vessel"]]
    answer = "4 unique tags: 2 Pump, 1 Flow transmitter, 1 Vessel (mock)."
    events = (_head(route, plan)
              + _tool_events(1, "read_document", {"file_id": "f_mock", "kind": "pid"}, "doc_1: 4 tiles read")
              + _tool_events(2, "extract_pid_tags", {"doc_id": "doc_1"}, answer, artifacts=(0,)) + _finish(3, answer))
    return Script(route, plan, events, [("pid_tags_mock.xlsx", ArtifactKind.XLSX,
                                         xlsx_bytes(["Tag", "Equipment type"], rows), answer)], answer)


def agent_script(message: str) -> Script:
    route = _route(TaskType.GENERAL, "Default: no rule matched (mock)", layer="default")
    plan = [PlanStep(index=1, title="Answer from the SOPs", tool="answer_question"),
            PlanStep(index=2, title="Report", tool="finish")]
    answer = (f"Mock answer to: {message[:120]}\n\n100 ppm of H2S is IDLH [1].\n\n"
              "Sources:\n[1] osha_h2s_fact_sheet.pdf, p.1")
    events = (_head(route, plan) + _tool_events(1, "answer_question", {"question": message}, answer, model="general")
              + _finish(2, answer))
    return Script(route, plan, events, [], answer)


def script_for(request: TaskCreate) -> Script:
    if request.scenario == Scenario.INSPECTION_NOTE:
        return inspection_script()
    if request.scenario == Scenario.CODE_CALC:
        return code_script()
    if request.scenario == Scenario.PID_TAGS:
        return pid_script()
    return agent_script(request.message)


# ---------------------------------------------------------------- in-memory state
@dataclass
class MockTask:
    request: TaskCreate
    task_id: str
    created_at: datetime
    started: float
    script: Script
    release_s: float
    artifacts: list[Artifact] = field(default_factory=list)
    cancelled_after: Optional[int] = None     # events released when the cancel arrived

    def events(self) -> list[AgentEvent]:
        total = len(self.script.events)
        released = min(total, int((time.monotonic() - self.started) / self.release_s) + 1)
        if self.cancelled_after is not None:
            released = min(released, self.cancelled_after)
        out = [self._event(i + 1, raw) for i, raw in enumerate(self.script.events[:released])]
        if self.cancelled_after is not None:
            error = ErrorInfo(code="CANCELLED", message=ERROR_CODES["CANCELLED"]).model_dump()
            out.append(AgentEvent(seq=len(out) + 1, task_id=self.task_id, ts=now(), type=EventType.ERROR,
                                  title="Cancelled", data={"error": error}))
        return out

    def _event(self, seq: int, raw: dict[str, Any]) -> AgentEvent:
        data = copy.deepcopy(raw["data"])
        ref = data.get("artifact")
        if isinstance(ref, str) and ref.startswith("$artifact:"):
            art = self.artifacts[int(ref.split(":")[1])]
            data["artifact"] = art.model_dump(mode="json")
            raw = {**raw, "title": art.filename}
        return AgentEvent(seq=seq, task_id=self.task_id, ts=self.created_at, type=EventType(raw["type"]),
                          step=raw.get("step"), title=raw["title"], data=data)

    def status(self) -> TaskStatus:
        if self.cancelled_after is not None:
            return TaskStatus.CANCELLED
        events = self.events()
        return TaskStatus.SUCCEEDED if len(events) == len(self.script.events) else TaskStatus.RUNNING

    def state(self) -> TaskState:
        status, events = self.status(), self.events()
        released = [e.data["artifact"]["artifact_id"] for e in events if e.type == EventType.ARTIFACT]
        done = status != TaskStatus.RUNNING
        return TaskState(
            task_id=self.task_id, status=status, mode=self.request.mode, scenario=self.request.scenario,
            message=self.request.message, file_ids=self.request.file_ids, route=self.script.route,
            plan=self.script.plan, final_answer=self.script.answer if status == TaskStatus.SUCCEEDED else None,
            artifacts=[a for a in self.artifacts if a.artifact_id in released],
            error=ErrorInfo(code="CANCELLED", message=ERROR_CODES["CANCELLED"]) if status == TaskStatus.CANCELLED else None,
            created_at=self.created_at, started_at=self.created_at, finished_at=now() if done else None,
            elapsed_s=round(time.monotonic() - self.started, 1))


class MockState:
    def __init__(self) -> None:
        self.lock = threading.Lock()
        self.tasks: dict[str, MockTask] = {}
        self.files: dict[str, FileRef] = {}
        self.artifacts: dict[str, tuple[Artifact, bytes]] = {}
        self.audit: list[AuditRecord] = []
        self.release_s = float(load_fixture().get("release_every_s", DEFAULT_RELEASE_S))

    def record(self, kind: str, name: str, task_id: Optional[str] = None, **detail: Any) -> None:
        self.audit.append(AuditRecord(ts=now(), task_id=task_id, kind=kind, name=name, detail=detail))

    def create_task(self, request: TaskCreate) -> MockTask:
        task = MockTask(request=request, task_id=new_id("t"), created_at=now(), started=time.monotonic(),
                        script=script_for(request), release_s=self.release_s)
        for filename, kind, content, preview in task.script.files:
            art = Artifact(artifact_id=new_id("a"), task_id=task.task_id, filename=filename, kind=kind,
                           size_bytes=len(content), created_at=task.created_at, download_url="",
                           preview=preview[:500])
            art.download_url = f"{API_PREFIX}/artifacts/{art.artifact_id}"
            task.artifacts.append(art)
            self.artifacts[art.artifact_id] = (art, content)
        self.tasks[task.task_id] = task
        self.record("system", "task_created", task.task_id, mode=request.mode.value, files=len(request.file_ids))
        self.record("llm", "general", task.task_id, purpose="plan (mock)")
        return task


