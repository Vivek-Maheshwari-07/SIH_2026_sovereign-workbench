# ---------------------------------------------------------------- errors + header (same shape as the backend)
def error_response(status: int, code: str, message: Optional[str] = None) -> JSONResponse:
    body = ApiError(error=ErrorInfo(code=code, message=message or ERROR_CODES.get(code, code)))
    return JSONResponse(status_code=status, content=body.model_dump(mode="json"),
                        headers={"X-Contract-Version": CONTRACT_VERSION})


def fail(status: int, code: str, message: Optional[str] = None) -> HTTPException:
    return HTTPException(status_code=status, detail={"code": code, "message": message or ERROR_CODES[code]})


@app.middleware("http")
async def _contract_header(request: Request, call_next):
    response = await call_next(request)
    response.headers["X-Contract-Version"] = CONTRACT_VERSION
    return response


@app.exception_handler(RequestValidationError)
async def _validation(request: Request, exc: RequestValidationError) -> JSONResponse:
    return error_response(422, "BAD_REQUEST", f"Request body failed validation: {exc.errors()}")


@app.exception_handler(StarletteHTTPException)
async def _http(request: Request, exc: StarletteHTTPException) -> JSONResponse:
    if isinstance(exc.detail, dict):
        return error_response(exc.status_code, exc.detail["code"], exc.detail.get("message"))
    return error_response(exc.status_code, "INTERNAL" if exc.status_code >= 500 else "BAD_REQUEST", str(exc.detail))


def get_task_or_404(task_id: str) -> MockTask:
    task = state.tasks.get(task_id)
    if task is None:
        raise fail(404, "TASK_NOT_FOUND")
    return task


