@app.post(f"{API_PREFIX}/files", response_model=FileRef)
async def upload(file: UploadFile = File(...)) -> FileRef:
    name = file.filename or "upload"
    suffix = name.rsplit(".", 1)[-1].lower() if "." in name else ""
    if suffix not in ALLOWED_UPLOAD_TYPES:
        raise fail(415, "UNSUPPORTED_FILE")
    content = await file.read()
    ref = FileRef(file_id=new_id("f"), filename=name, mime_type=file.content_type or "application/octet-stream",
                  size_bytes=len(content), is_image=suffix in IMAGE_SUFFIXES,
                  pages=1 if suffix == "pdf" else None, has_text_layer=False if suffix == "pdf" else None)
    state.files[ref.file_id] = ref
    return ref


@app.post(f"{API_PREFIX}/route", response_model=RouteDecision)
def route(request: RouteRequest) -> RouteDecision:
    if any(state.files.get(f) is not None and state.files[f].is_image for f in request.file_ids):
        return _route(TaskType.VISION, "Rule: Image attached -> vision-capable model")
    text = request.message.lower()
    if any(word in text for word in ("code", "python", "function", "script")):
        return _route(TaskType.CODING, "Rule: Coding keywords -> code specialist model")
    if any(word in text for word in ("report", "sop", "summar", "approval note", "presentation")):
        return _route(TaskType.DOCUMENT, "Rule: Document keywords -> document agent")
    return _route(TaskType.GENERAL, "Default: no rule matched (mock)", layer="default")


@app.post(f"{API_PREFIX}/tasks", response_model=TaskCreated, status_code=202)
def create_task(request: TaskCreate) -> TaskCreated:
    if request.mode == TaskMode.GUIDED and request.scenario is None:
        raise fail(422, "BAD_REQUEST", "Guided mode needs a scenario.")
    with state.lock:
        task = state.create_task(request)
    return TaskCreated(task_id=task.task_id, status=TaskStatus.QUEUED)


@app.get(f"{API_PREFIX}/tasks/{{task_id}}", response_model=TaskState)
def get_task(task_id: str) -> TaskState:
    return get_task_or_404(task_id).state()


@app.get(f"{API_PREFIX}/tasks/{{task_id}}/events", response_model=EventsPage)
def get_events(task_id: str, after: int = Query(default=0, ge=0)) -> EventsPage:
    task = get_task_or_404(task_id)
    events = task.events()
    page = [e for e in events if e.seq > after]
    done = task.status() != TaskStatus.RUNNING
    if done and not any(r.task_id == task_id and r.name == "task_finished" for r in state.audit):
        state.record("system", "task_finished", task_id, status=task.status().value)
    return EventsPage(task_id=task_id, events=page, next_seq=page[-1].seq if page else after, done=done)


@app.post(f"{API_PREFIX}/tasks/{{task_id}}/cancel", response_model=TaskState)
def cancel(task_id: str) -> TaskState:
    task = get_task_or_404(task_id)
    with state.lock:
        if task.status() == TaskStatus.RUNNING:
            task.cancelled_after = len(task.events())
            state.record("system", "task_cancelled", task_id)
    return task.state()


@app.get(f"{API_PREFIX}/artifacts/{{artifact_id}}")
def artifact(artifact_id: str) -> Response:
    if ".." in artifact_id or "/" in artifact_id or "\\" in artifact_id:
        raise fail(400, "BAD_REQUEST", "artifact_id must not contain path characters")
    found = state.artifacts.get(artifact_id)
    if found is None:
        raise fail(404, "FILE_NOT_FOUND", f"no artifact with id {artifact_id!r}")
    art, content = found
    return Response(content, media_type=MEDIA_TYPES.get(art.kind, "application/octet-stream"),
                    headers={"Content-Disposition": f'attachment; filename="{art.filename}"'})


